class CurtailmentProposal(BaseModel):
    """
    A Redispatch 2.0 curtailment proposal generated by the Gemini copilot.

    HITL invariant INV-009:
        SCADA write is unconditionally blocked when operator_approved == False.

    Regulatory invariant INV-010:
        legal_basis must be non-empty (BNetzA transparency).
    """

    asset_id: str = Field(..., description="Target PV asset identifier")
    curtailment_mw: float = Field(
        ..., ge=0.0, description="Proposed MW reduction from asset output"
    )
    legal_basis: str = Field(
        ..., min_length=1, description="EnWG paragraph, e.g. 'EnWG §13 Abs. 1'"
    )
    operator_approved: bool = Field(
        default=False,
        description=(
            "Must be set to True by an authenticated human operator "
            "before any SCADA write is permitted (EU AI Act / HITL gatekeeper)"
        ),
    )
    approval_timestamp: Optional[datetime] = Field(
        default=None,
        description="UTC timestamp of operator approval",
    )
    approving_operator_id: Optional[str] = Field(
        default=None,
        description="Identifier of the approving operator",
    )
    gemini_reasoning: str = Field(
        default="",
        description="Full Gemini model reasoning for EU AI Act audit trail",
    )

    @model_validator(mode="after")
    def scada_write_gatekeeper(self) -> CurtailmentProposal:
        """
        INV-009: Enforce that approval fields are consistent.
        If operator_approved is True, both timestamp and operator_id must be set.
        """
        if self.operator_approved:
            if self.approval_timestamp is None or self.approving_operator_id is None:
                raise ValueError(
                    "operator_approved=True requires both approval_timestamp "
                    "and approving_operator_id to be set."
                )
        return self

    @property
    def scada_write_permitted(self) -> bool:
        """
        Hard gatekeeper property.
        SCADA write is ONLY permitted when all three conditions hold:
          1. operator_approved == True
          2. approval_timestamp is set
          3. approving_operator_id is set
        """
        return (
            self.operator_approved
            and self.approval_timestamp is not None
            and self.approving_operator_id is not None
        )


class CopilotOutput(BaseModel):
    """Full output contract for Module 4 (04_copilot.py)."""

    incident_id: str = Field(..., description="Unique incident UUID")
    generated_at: datetime = Field(..., description="UTC generation timestamp")
    model_version: str = Field(default="gemini-2.5-flash")
    proposals: list[CurtailmentProposal] = Field(
        default_factory=list,
        description="List of BNetzA Redispatch 2.0 curtailment proposals",
    )
    incident_summary: str = Field(
        ..., description="Human-readable incident summary from Gemini"
    )
    redispatch_volume_mw: float = Field(
        ..., ge=0.0, description="Total proposed redispatch volume in MW"
    )
    scada_write_blocked: bool = Field(
        ...,
        description="True if any proposal is pending human approval (should always start True)",
    )
