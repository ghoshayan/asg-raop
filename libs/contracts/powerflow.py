"""
libs/contracts/powerflow.py

Pydantic v2 data contracts for Module 3 (grid physics) and Module 4 (copilot).
Covers SimBench topology metadata, AC load-flow results, and
BNetzA Redispatch 2.0 curtailment proposals with HITL gatekeeper.
"""

from __future__ import annotations

from datetime import datetime
from typing import Optional

from pydantic import BaseModel, Field, field_validator, model_validator

# ---------------------------------------------------------------------------
# Module 3 contracts
# ---------------------------------------------------------------------------


class GridTopology(BaseModel):
    """Metadata for a loaded SimBench / pandapower network."""

    topology_name: str = Field(
        ..., description="Identifier, e.g. 'simbench-mv-rural'"
    )
    n_buses: int = Field(..., gt=0, description="Number of buses in the network")
    n_lines: int = Field(..., gt=0, description="Number of lines/branches")
    voltage_level_kv: float = Field(
        ..., gt=0.0, description="Nominal voltage level in kV"
    )


class PowerFlowOutput(BaseModel):
    """
    Output contract for Module 3 (03_grid_physics.py).

    Physical invariants: INV-007, INV-008.
    EN 50160 voltage band: V_bus ∈ [0.85, 1.15] p.u.
    """

    topology_name: str
    is_overloaded: bool = Field(
        ..., description="True if any line exceeds 80 % thermal loading"
    )
    max_line_loading_pct: float = Field(
        ..., ge=0.0, description="Worst-case line loading in percent"
    )
    min_bus_voltage_pu: float = Field(
        ..., description="Minimum bus voltage across all buses (p.u.)"
    )
    max_bus_voltage_pu: float = Field(
        ..., description="Maximum bus voltage across all buses (p.u.)"
    )
    critical_lines: list[str] = Field(
        default_factory=list,
        description="Names of lines exceeding 80 % thermal loading",
    )
    redispatch_required: bool = Field(
        ...,
        description=(
            "True when BNetzA Redispatch 2.0 trigger conditions are met "
            "(overload OR voltage out of EN 50160 band)"
        ),
    )
    n1_contingency_violated: bool = Field(
        default=False,
        description="True if any N-1 contingency scenario causes overload",
    )
    effective_solar_injected_mw: float = Field(
        ..., ge=0.0, description="P_effective injected as PV generation in MW"
    )

    @field_validator("min_bus_voltage_pu")
    @classmethod
    def check_lower_voltage(cls, v: float) -> float:
        """INV-007: EN 50160 lower voltage band."""
        if v < 0.85:
            raise ValueError(
                f"min_bus_voltage_pu = {v:.4f} p.u. violates EN 50160 lower limit "
                f"of 0.85 p.u. Redispatch intervention required."
            )
        return v

    @field_validator("max_bus_voltage_pu")
    @classmethod
    def check_upper_voltage(cls, v: float) -> float:
        """INV-008: EN 50160 upper voltage band."""
        if v > 1.15:
            raise ValueError(
                f"max_bus_voltage_pu = {v:.4f} p.u. violates EN 50160 upper limit "
                f"of 1.15 p.u. Redispatch intervention required."
            )
        return v


