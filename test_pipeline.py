# INT-003: ELPV Sample Fixture Image & Monotonicity Verification
# ---------------------------------------------------------------------------


def test_inv_004_fixture_image_monotonicity():
    """
    PHYSICAL INVARIANT: Greater defect area in EL image must monotonically increase
    degradation scalar and reduce effective injected generation.
    """
    samples_dir = PROJECT_ROOT / "tests" / "fixtures" / "elpv_samples"
    functional_path = samples_dir / "functional_cell.png"
    damaged_path = samples_dir / "severely_damaged.png"

    assert functional_path.exists(), f"Missing fixture: {functional_path}"
    assert damaged_path.exists(), f"Missing fixture: {damaged_path}"

    base_mw = 100.0
    res_func = _vision_mod.run(
        predicted_solar_mw=base_mw,
        asset_id="PV-CLEAN-01",
        image_path=functional_path,
    )
    res_damaged = _vision_mod.run(
        predicted_solar_mw=base_mw,
        asset_id="PV-DAMAGED-01",
        image_path=damaged_path,
    )

    # Invariants on degradation scalar bounds
    assert 0.0 <= res_func["degradation_scalar"] <= 1.0
    assert 0.0 <= res_damaged["degradation_scalar"] <= 1.0

    # Monotonicity checks
    assert res_func["degradation_scalar"] < res_damaged["degradation_scalar"], (
        f"Functional degradation ({res_func['degradation_scalar']:.3f}) should be lower "
        f"than severely damaged ({res_damaged['degradation_scalar']:.3f})"
    )
    assert res_func["effective_solar_mw"] > res_damaged["effective_solar_mw"], (
        f"Functional effective MW ({res_func['effective_solar_mw']:.2f}) should exceed "
        f"damaged effective MW ({res_damaged['effective_solar_mw']:.2f})"
    )


